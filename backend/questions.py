# Кодируем индекс в одно число: tier * 1000 + position_in_tier.
# Это позволяет хранить одно множество used_indices как и раньше.
_TIER_STRIDE = 1000


def _flat_pool(level: str, kind: str) -> list[tuple[int, str]]:
    """Все вопросы уровня/типа в виде [(encoded_idx, text), ...]."""
    out: list[tuple[int, str]] = []
    for tier_idx, tier in enumerate(QUESTIONS[level][kind]):
        for pos, text in enumerate(tier):
            out.append((tier_idx * _TIER_STRIDE + pos, text))
    return out


def pick_tier(turn_index: int, t1_end: int, t2_end: int) -> int:
    """Возвращает 0|1|2 в зависимости от того, какой ход сейчас идёт."""
    if turn_index < t1_end:
        return 0
    if turn_index < t2_end:
        return 1
    return 2


def get_question(
    level: str,
    kind: str,
    used_indices: Iterable[int] | None = None,
    turn_index: int = 0,
    t1_end: int = 8,
    t2_end: int = 16,
) -> tuple[int, str]:
    """Случайный вопрос из текущей подгруппы (по turn_index/порогам).

    Если в выбранном тире всё использовано — берём из следующего по порядку
    (тир-3 → тир-2 → тир-1 → сброс), чтобы игра не зависла.
    """
    used = set(used_indices or [])
    target_tier = pick_tier(turn_index, t1_end, t2_end)

    # Пробуем целевой тир, потом более старшие, потом младшие, потом сброс.
    tier_order = [target_tier]
    for t in (target_tier + 1, target_tier + 2):
        if 0 <= t < 3 and t not in tier_order:
            tier_order.append(t)
    for t in (target_tier - 1, target_tier - 2):
        if 0 <= t < 3 and t not in tier_order:
            tier_order.append(t)

    for tier_idx in tier_order:
        tier = QUESTIONS[level][kind][tier_idx]
        candidates = [
            (tier_idx * _TIER_STRIDE + pos, text)
            for pos, text in enumerate(tier)
            if (tier_idx * _TIER_STRIDE + pos) not in used
        ]
        if candidates:
            return random.choice(candidates)

    # Всё использовано — сбрасываем и берём из целевого тира заново.
    tier = QUESTIONS[level][kind][target_tier]
    pos = random.randrange(len(tier))
    return target_tier * _TIER_STRIDE + pos, tier[pos]
